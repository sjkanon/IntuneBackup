function main() {
  const checkOnly = process.argv.includes("--check");
  const dumpMissing = process.argv.includes("--missend");
  const quiet = dumpMissing;
  const log = (...a) => (quiet ? null : console.log(...a));
  const templates = readTemplates(TEMPLATE_DIR);
  const assignments = fs.existsSync(ASSIGNMENTS_PATH) ? JSON.parse(fs.readFileSync(ASSIGNMENTS_PATH, "utf8")) : {};
  const manifest = fs.existsSync(MANIFEST_PATH) ? JSON.parse(fs.readFileSync(MANIFEST_PATH, "utf8")) : { policies: [] };
  const manifestByTarget = new Map(manifest.policies.map((p) => [p.target, p]));
  const vocab = fs.existsSync(CONTROLS_PATH) ? JSON.parse(fs.readFileSync(CONTROLS_PATH, "utf8")) : { iso27001: { controls: [] } };
  const isoById = new Map(vocab.iso27001.controls.map((c) => [c.id, c]));

  const ca = loadCaLinks();
  const known = new Set(templates.map((t) => t.baseName));
  for (const baseName of Object.keys(ca.snapshot.koppelingen || {})) {
    if (!known.has(baseName)) console.warn(`Let op: CA-koppeling naar ${baseName}, maar dat template bestaat hier niet — pas docs/policies.json in de CA-Policies-repo aan.`);
  }
  if (!ca.root && !quiet) log("CA-Policies-repo niet ernaast: de CA-koppelingen komen uit IntuneTemplate/_ca.json.");

  const ctx = { assignments, manifestByTarget, manifest, isoById, ca };
  const files = ca.content ? [{ file: CA_SNAPSHOT_PATH, content: ca.content }] : [];
  const translators = [];

  for (const lang of LANGS) {
    V = new Translator(lang);
    translators.push(V);
    const add = (file, content) => files.push({ file: variantPath(file, lang), content });

    add(path.join(REPO_ROOT, "docs", "OVERZICHT.md"), overviewDocument(templates, ctx));
    add(path.join(TEMPLATE_DIR, "README.md"), overviewReadme(templates, ctx));

    for (const platform of Object.keys(PLATFORMS)) {
      const list = templates.filter((t) => parseBaseName(t.baseName).platform === platform);
      if (list.length === 0) continue;
      add(path.join(TEMPLATE_DIR, platform, "README.md"), platformReadme(platform, list, ctx));
    }

    // Eén document per policy, naast de JSON.
    for (const template of templates) add(template.filePath.replace(/\.json$/, ".md"), policyDocument(template, ctx));
  }

  if (dumpMissing) {
    reportMissing(translators, process.argv, "generate-docs.js");
    return;
  }

  const stale = [];
  for (const { file, content } of files) {
    const rel = path.relative(REPO_ROOT, file).split(path.sep).join("/");
    const before = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (before === content) {
      log(`  ongewijzigd  ${rel}`);
      continue;
    }
    stale.push(rel);
    if (checkOnly) {
      log(`  VEROUDERD    ${rel}`);
      continue;
    }
    fs.writeFileSync(file, content);
    log(`  ${before === null ? "nieuw       " : "bijgewerkt  "} ${rel}`);
  }

  reportMissing(translators, process.argv, "generate-docs.js");

  if (checkOnly && stale.length > 0) {
    console.error(`\n${stale.length} README('s) lopen achter. Draai: node scripts/generate-docs.js`);
    process.exit(1);
  }
  console.log(`\n${files.length} README('s) gecontroleerd, ${stale.length} ${checkOnly ? "verouderd" : "geschreven"}.`);
}

main();
