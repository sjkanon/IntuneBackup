function assignmentLabel(assignments, displayName) {
  const list = assignments[displayName];
  if (!list || list.length === 0) return "—";
  return list
    .map((a) => {
      const type = a.target["@odata.type"] || "";
      if (type.includes("allDevices")) return "All Devices";
      if (type.includes("allLicensedUsers")) return "All Users";
      if (type.includes("exclusionGroup")) return V.t({ nl: "groep (uitsluiting)", en: "group (exclusion)", fr: "groupe (exclusion)" });
      if (type.includes("group")) return V.t({ nl: "groep", en: "group", fr: "groupe" });
      return type.replace("#microsoft.graph.", "");
    })
    .join(", ");
}

/** Het aantal instellingen dat een policy werkelijk zet — de uitgeklapte telling. */
function settingCount(template) {
  if (template.type === "Catalog") return flattenSettings(template.raw.settings).settings.length;
  if (template.type === "Admin") return (template.raw.added || []).length;
  return "—";
}

function escapePipes(text) {
  return String(text).replace(/\|/g, "\\|");
}

/**
 * Waarde leesbaar maken. Bij een keuze-instelling is de waarde de settingDefinitionId met een
 * suffix eraan geplakt (`..._requiresecuritydevice_true`); dat voorvoegsel herhalen maakt de
 * tabel onleesbaar, dus alleen het suffix blijft over.
 */
function shortValue(id, value) {
  if (value === null || value === undefined) return "—";
  let text = String(value);
  if (id && text.startsWith(id + "_")) text = text.slice(id.length + 1);
  if (text === "") return V.t({ nl: "*(leeg)*", en: "*(empty)*", fr: "*(vide)*" });
  if (text.length > 110) text = text.slice(0, 107) + "…";
  return text;
}

/**
 * Klapt een settingInstance-boom uit met behoud van de nesting, want die nesting is
 * betekenisvol: een kind is alleen actief als zijn parent op de juiste waarde staat.
 * flattenSettings() gooit dat weg — prima voor een vergelijking, niet voor documentatie.
 */
function settingRows(instance, depth, rows) {
  if (!instance || typeof instance !== "object") return;
  const odataType = instance["@odata.type"] || "";
  const id = instance.settingDefinitionId;

  if (odataType.endsWith("ChoiceSettingInstance")) {
    const value = instance.choiceSettingValue || {};
    rows.push({ depth, id, value: shortValue(id, value.value) });
    for (const child of value.children || []) settingRows(child, depth + 1, rows);
  } else if (odataType.endsWith("ChoiceSettingCollectionInstance")) {
    const values = instance.choiceSettingCollectionValue || [];
    rows.push({ depth, id, value: values.map((v) => shortValue(id, v.value)).join(", ") });
    for (const v of values) for (const child of v.children || []) settingRows(child, depth + 1, rows);
  } else if (odataType.endsWith("SimpleSettingInstance")) {
    const value = instance.simpleSettingValue || {};
    const secret = (value["@odata.type"] || "").includes("Secret");
    const secretText = V.t({
      nl: "*(geheim — alleen geldig in de brontenant)*",
      en: "*(secret — only valid in the source tenant)*",
      fr: "*(secret — valable uniquement dans le tenant source)*",
    });
    rows.push({ depth, id, value: secret ? secretText : shortValue(null, value.value) });
  } else if (odataType.endsWith("SimpleSettingCollectionInstance")) {
    const values = (instance.simpleSettingCollectionValue || []).map((v) => String(v.value));
    rows.push({ depth, id, value: values.join(", ") });
  } else if (odataType.endsWith("GroupSettingCollectionInstance")) {
    const groups = instance.groupSettingCollectionValue || [];
    rows.push({ depth, id, value: groups.length > 1 ? `*(${groups.length} items)*` : V.t({ nl: "*(groep)*", en: "*(group)*", fr: "*(groupe)*" }) });
    groups.forEach((group, i) => {
      if (groups.length > 1) rows.push({ depth: depth + 1, id: null, value: null, separator: `item ${i + 1}` });
      for (const child of group.children || []) settingRows(child, depth + 1, rows);
    });
  } else {
    rows.push({ depth, id, value: V.t({ nl: `*(onbekend type ${odataType})*`, en: `*(unknown type ${odataType})*`, fr: `*(type inconnu ${odataType})*` }) });
  }
}

/** Eigenschappen van een compliance-, device- of app protection-policy als tabelrijen. */
const BODY_SKIP = new Set(["@odata.type", "displayName", "description", "name", "roleScopeTagIds", "settings", "platforms", "technologies", "templateReference"]);

function bodyRows(raw, prefix = "", rows = []) {
  for (const [key, value] of Object.entries(raw)) {
    if (BODY_SKIP.has(key) && !prefix) continue;
    const label = prefix ? `${prefix}.${key}` : key;
    if (value && typeof value === "object" && !Array.isArray(value)) bodyRows(value, label, rows);
    else if (Array.isArray(value)) {
      if (value.length === 0) rows.push({ id: label, value: "—" });
      else if (value.every((v) => typeof v !== "object")) rows.push({ id: label, value: value.join(", ") });
      else value.forEach((v, i) => bodyRows(v, `${label}[${i}]`, rows));
    } else rows.push({ id: label, value: value === null ? "—" : truncateScalar(String(value)) });
  }
  return rows;
}

/**
 * Losse waarden afkappen op dezelfde lengte als shortValue() bij de settings-tabellen. Een
 * custom macOS-profiel draagt zijn hele mobileconfig als base64 in `payload`; onafgekapt is dat
 * duizenden tekens in één tabelcel, en dan is de tabel eromheen niet meer te lezen. Alleen
 * scalairen: lijstwaarden (managedUniversalLinks bij App Protection) blijven volledig, want
 * daar is de inhoud van de lijst juist wat je wil zien.
 */
function truncateScalar(text) {
  return text.length > 110 ? `${text.slice(0, 107)}…` : text;
}

/**
 * De normen uit `controls` in het manifest, als tabel onder de policy. Alleen de labels: wat een
 * control betekent en wat er organisatorisch naast nodig is staat in COMPLIANCE.md, en dat hier
 * herhalen zou honderdvijftig kopieën opleveren die elk apart verouderen.
 */
const CONTROL_FRAMEWORKS = [
  ["iso", "ISO/IEC 27001:2022"],
  ["nis2", "NIS2 art. 21(2)"],
  ["cis", "CIS Controls v8.1"],
  ["nistcsf", "NIST CSF 2.0"],
];

/**
 * Een label in de taal van het document. ISO krijgt de officiële Engelse titel uit de
 * vocabulaire (`titelEn`) en in het Frans de vertaling van de NEN-titel; NIS2 gaat door het
 * woordenboek. CIS en NIST CSF zijn al Engels en blijven dat in elke taal.
 */
function controlLabel(key, label, ctx) {
  const text = String(label);
  if (key === "cis") return text.replace(/^CIS Controls v8\.1 /, "");
  if (V.lang === "nl" || key === "nistcsf") return text;
  if (key === "iso") {
    const m = text.match(/^(A\.\d+\.\d+)(?:\s|$)/);
    const c = m && ctx.isoById.get(m[1]);
    if (!c) return text;
    return `${c.id} ${V.lang === "en" ? c.titelEn : V.d(c.titelNen)}`;
  }
  return V.d(text);
}

function controlsSection(controls, ctx) {
  const rows = CONTROL_FRAMEWORKS.filter(([key]) => (controls[key] || []).length > 0).map(
    ([key, label]) => `| ${label} | ${controls[key].map((c) => escapePipes(controlLabel(key, c, ctx))).join("<br>")} |`
  );
  if (rows.length === 0) return [];
  return [
    V.t({ nl: "## Normen", en: "## Standards", fr: "## Normes" }),
    "",
    V.t({ nl: "| Kader | Controls |", en: "| Framework | Controls |", fr: "| Référentiel | Mesures |" }),
    "|---|---|",
    ...rows,
    "",
    V.t({
      nl: `Wat dit per norm betekent en wat er organisatorisch naast nodig is: [COMPLIANCE.md](${V.link("../../../docs/COMPLIANCE.md")}).`,
      en: `What this means per standard and what is needed organisationally alongside it: [COMPLIANCE.en.md](${V.link("../../../docs/COMPLIANCE.md")}).`,
      fr: `Ce que cela signifie pour chaque norme et ce qui reste nécessaire sur le plan organisationnel : [COMPLIANCE.fr.md](${V.link("../../../docs/COMPLIANCE.md")}).`,
    }),
    "",
  ];
}

/**
 * De koppeling met Conditional Access, van de Intune-kant gezien: per Intune-policy de CA-policies
 * die erop leunen. Uit de CA-Policies-repo als die ernaast staat (en dan ook als nieuwe inhoud van
 * _ca.json), anders uit _ca.json zelf.
 */
function loadCaLinks() {
  const root = CA_SIBLINGS.find((d) => fs.existsSync(path.join(d, "docs", "policies.json")) && fs.existsSync(path.join(d, "CATemplate")));
  if (!root) {
    const snapshot = fs.existsSync(CA_SNAPSHOT_PATH) ? JSON.parse(fs.readFileSync(CA_SNAPSHOT_PATH, "utf8")) : { koppelingen: {} };
    return { root: null, snapshot, content: null };
  }
  const data = JSON.parse(fs.readFileSync(path.join(root, "docs", "policies.json"), "utf8"));
  const groups = data.groepen || {};
  const koppelingen = {};
  for (const ca of Object.keys(data.policies).sort()) {
    const file = path.join(root, "CATemplate", `${ca}.json`);
    if (!fs.existsSync(file)) continue;
    const inner = JSON.parse(JSON.parse(fs.readFileSync(file, "utf8")).JSON);
    for (const link of data.policies[ca].intune || []) {
      for (const target of link.targets.flatMap((t) => (t.startsWith("@") ? groups[t.slice(1)] || [] : [t]))) {
        const baseName = path.posix.basename(target);
        const list = (koppelingen[baseName] = koppelingen[baseName] || []);
        if (!list.some((x) => x.ca === ca)) list.push({ ca, displayName: inner.displayName, state: inner.state, waarom: link.waarom });
      }
    }
  }
  const snapshot = {
    _comment: [
      "Gegenereerd door scripts/generate-docs.js uit docs/policies.json in de CA-Policies-repo — niet met de hand bijwerken.",
      "Per Intune-policy de Conditional Access-policies die erop leunen, en waarom. Een kopie, zodat de",
      "README per policy ook in CI (zonder de CA-repo ernaast) dezelfde sectie 'Conditional Access' krijgt.",
      "Wijzigen gebeurt in de CA-Policies-repo; draai daarna hier generate-docs.js met die repo ernaast.",
    ],
    koppelingen: Object.fromEntries(Object.keys(koppelingen).sort().map((k) => [k, koppelingen[k]])),
  };
  return { root, snapshot, content: JSON.stringify(snapshot, null, 2) + "\n" };
}

const CA_STATE = { enabled: "enabled", enabledForReportingButNotEnforced: "report-only", disabled: "disabled" };

