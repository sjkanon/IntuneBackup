// ---------------------------------------------------------------------------------------------

function main() {
  const opts = parseArgs(process.argv.slice(2));
  const dumpMissing = process.argv.includes("--missend");
  for (const file of [MANIFEST_PATH, CONTROLS_PATH]) {
    if (!fs.existsSync(file)) {
      console.error(`${path.relative(REPO_ROOT, file)} ontbreekt — zonder dat bestand valt er niets te verantwoorden.`);
      process.exit(1);
    }
  }
  const templates = readTemplates(TEMPLATE_DIR);
  const manifest = readJson(MANIFEST_PATH);
  const assignments = fs.existsSync(ASSIGNMENTS_PATH) ? readJson(ASSIGNMENTS_PATH) : {};
  const voc = indexVocabulary(readJson(CONTROLS_PATH));
  const { map: checkIds, present: baselinePresent } = checkIdsByTarget(templates);
  const ca = opts.noCa ? { present: false, uitgezet: true, path: opts.caControls, policies: [] } : readConditionalAccess(opts.caControls);

  if (!baselinePresent) console.warn("Let op: baseline/intune/baseline-v1.0.json ontbreekt — geen checkId's. Draai eerst generate-baseline.js.");
  if (!ca.present && !ca.uitgezet) console.warn(`Conditional Access niet meegenomen: ${ca.path} bestaat niet.`);

  const licenties = fs.existsSync(LICENTIES_PATH) ? readJson(LICENTIES_PATH) : null;
  const templateByTarget = new Map(templates.map((t) => [t.baseName, t]));

  // Een licentieregel die naar een verdwenen template wijst, belooft een dekking die er niet is.
  if (licenties && !dumpMissing) {
    for (const lic of licenties.licenties) {
      for (const t of lic.ontgrendelt.intune || []) {
        if (!templateByTarget.has(t)) console.warn(`  licentie "${lic.displayName}" noemt ${t}, maar dat template bestaat niet`);
      }
      for (const deel of lic.gedeeltelijk || []) {
        if (!templateByTarget.has(deel.target)) console.warn(`  licentie "${lic.displayName}" noemt ${deel.target}, maar dat template bestaat niet`);
      }
    }
  }

  const ctx = { voc, manifest, assignments, templates, checkIds, ca, baselinePresent, licenties, templateByTarget };
  const data = buildIndex(ctx);

  const translators = [];
  const outputs = LANGS.map((lang) => {
    V = new Translator(lang);
    translators.push(V);
    const content = [sectionIntro(ctx), sectionSummary(ctx, data), sectionIso(ctx, data), sectionNis2(ctx, data), sectionCis(ctx, data), sectionCsf(ctx, data), sectionKeuzes(ctx, data), sectionLicenties(ctx), sectionSoa(ctx, data), sectionControle(ctx, data)].join("\n");
    return { file: variantPath(OUTPUT_PATH, lang), content };
  });

  if (dumpMissing) {
    reportMissing(translators, process.argv, "generate-compliance.js");
    return;
  }

  let stale = false;
  for (const { file, content } of outputs) {
    const rel = path.relative(REPO_ROOT, file);
    const before = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (before === content) {
      console.log(`  ongewijzigd  ${rel}`);
    } else if (opts.check) {
      console.error(`${rel} loopt achter. Draai: node scripts/generate-compliance.js`);
      stale = true;
    } else {
      fs.writeFileSync(file, content);
      console.log(`  ${before === null ? "nieuw       " : "bijgewerkt  "} ${rel}`);
    }
  }
  reportMissing(translators, process.argv, "generate-compliance.js");
  if (stale) process.exit(1);

  const { zonderControls, onbekend, afwijkend } = data.problems;
  for (const n of zonderControls) console.warn(`  zonder controls: ${n}`);
  for (const p of onbekend) console.warn(`  buiten de vocabulaire: ${p}`);
  for (const p of afwijkend) console.warn(`  afwijkende schrijfwijze: ${p}`);
  if (opts.strict && (zonderControls.length || onbekend.length || afwijkend.length)) {
    console.error(`\n--strict: ${zonderControls.length} zonder controls, ${onbekend.length} buiten de vocabulaire, ${afwijkend.length} afwijkend.`);
    process.exit(1);
  }
}

main();
