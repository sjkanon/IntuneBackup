<#
    Builds OfficeWeb-PlatformScript.ps1: Install-OfficeWeb.ps1 with Open-OfficeWeb.ps1 inside it,
    as one file to paste into CIPP (Intune -> Scripts) or to upload as an Intune platform script.

    Everything the devices run is in that one file; nothing is downloaded at run time. Run this
    again after a change to either script, and raise $Version in Install-OfficeWeb.ps1 and
    Detect-OfficeWeb.ps1.
#>

$ErrorActionPreference = 'Stop'
$install = Get-Content -LiteralPath (Join-Path $PSScriptRoot 'Install-OfficeWeb.ps1') -Raw
$open = Get-Content -LiteralPath (Join-Path $PSScriptRoot 'Open-OfficeWeb.ps1') -Raw

if ($open -match "(?m)^'@") { throw "Open-OfficeWeb.ps1 has a line starting with '@; that would end the here-string." }
if ($install -notmatch '# @@OPEN-SCRIPT@@') { throw 'Marker @@OPEN-SCRIPT@@ missing in Install-OfficeWeb.ps1.' }

$header = @"
# Generated by New-OfficeWebPlatformScript.ps1 from Install-OfficeWeb.ps1 and Open-OfficeWeb.ps1
# (sjkanon/IntuneBackup, IntuneTemplate/WIN/Apps/office-web-open). Do not edit by hand.
# Intune platform script: run as System (logged-on credentials: No), 64-bit PowerShell: Yes,
# signature check: No. Assign to SG-D-UEM-WIN-Shared.

"@
$embedded = "`$OpenScript = @'`r`n$($open.TrimEnd())`r`n'@"
$out = $header + $install.Replace('# @@OPEN-SCRIPT@@', $embedded)
$target = Join-Path $PSScriptRoot 'OfficeWeb-PlatformScript.ps1'
Set-Content -LiteralPath $target -Value $out -Encoding ASCII -NoNewline

$tokens = $null; $errors = $null
[void][System.Management.Automation.Language.Parser]::ParseFile($target, [ref]$tokens, [ref]$errors)
if ($errors.Count -gt 0) { throw "Generated script does not parse: $($errors[0].Message)" }
"$target ($([math]::Round((Get-Item $target).Length / 1KB, 1)) KB)"
